param([string] $CacheDirectory = '')
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# All scripts and notices are version-pinned and SHA-256 checked.
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Split-Path -Parent $here
$manifest = Get-Content -Raw -Encoding utf8 (Join-Path $root 'licenses/dependencies.json') | ConvertFrom-Json
$utf8 = New-Object Text.UTF8Encoding($false)
$marker = '<!--__OFFLINE_LIBRARIES__-->'
$template = [IO.File]::ReadAllText((Join-Path $here 'index.template.html'), $utf8)
if (-not $template.Contains($marker)) { throw 'Offline library marker not found.' }

function Get-TextHash([string] $Text) {
    $sha = [Security.Cryptography.SHA256]::Create()
    try { return ([BitConverter]::ToString($sha.ComputeHash($utf8.GetBytes($Text)))).Replace('-', '').ToLowerInvariant() }
    finally { $sha.Dispose() }
}

foreach ($document in $manifest.documents.PSObject.Properties) {
    $file = Join-Path $root $document.Name
    if (-not (Test-Path -LiteralPath $file)) { throw "Missing notice: $file" }
    if ((Get-FileHash -LiteralPath $file -Algorithm SHA256).Hash.ToLowerInvariant() -ne $document.Value) {
        throw "Notice hash mismatch: $file. Review the license manifest before building."
    }
}

[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
$blocks = New-Object System.Collections.Generic.List[string]
$blocks.Add('  <!-- Vendored dependencies: generated by offline/build_offline.ps1. No runtime network access is required. -->')
foreach ($dep in $manifest.runtime) {
    $cached = if ($CacheDirectory) { Join-Path $CacheDirectory ($dep.name + '.js') } else { '' }
    if ($cached -and (Test-Path -LiteralPath $cached)) {
        $code = [IO.File]::ReadAllText($cached, $utf8)
    } else {
        Write-Host ("Downloading {0} {1} ..." -f $dep.name, $dep.version)
        $response = Invoke-WebRequest -Uri $dep.url -UseBasicParsing -ErrorAction Stop
        $code = if ($response.Content -is [byte[]]) { $utf8.GetString($response.Content) } else { [string]$response.Content }
    }
    if ((Get-TextHash $code) -ne $dep.sha256) { throw ("Dependency hash mismatch: {0}" -f $dep.name) }
    $blocks.Add(("  <!-- {0} {1} | {2} | source: {3} -->" -f $dep.name, $dep.version, $dep.license, $dep.url))
    $blocks.Add('  <script>')
    $blocks.Add(($code -replace '(?i)</script', '<\/script'))
    $blocks.Add('  </script>')
}

# The same complete, readable license page is retained inside the portable file.
$licensePage = [IO.File]::ReadAllText((Join-Path $root 'licenses.html'), $utf8)
$licenseJson = ConvertTo-Json -InputObject $licensePage -Compress
$blocks.Add('  <script type="application/json" id="third-party-licenses">')
$blocks.Add($licenseJson.Replace('<', '\u003c'))
$blocks.Add('  </script>')
$output = $template.Replace($marker, [string]::Join([Environment]::NewLine, $blocks))
if ($output -match '<script\s+[^>]*src\s*=' -or $output.Contains($marker)) {
    throw 'Build validation failed: external script or unresolved marker.'
}
$outputPath = Join-Path $here 'index.html'
[IO.File]::WriteAllText($outputPath, $output, $utf8)
Write-Host ("Offline edition generated: {0} ({1:N0} bytes)" -f $outputPath, (Get-Item -LiteralPath $outputPath).Length)
